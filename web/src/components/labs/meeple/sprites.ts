/**
 * Every picture on this page, authored one pixel at a time.
 *
 * No icon set and no photography. A lucide glyph next to a 16x16 sprite is the
 * fastest way to break this style, because it is drawn on a different grid at a
 * different weight and antialiases where nothing else does. So the arrows, the
 * ticks and the game covers are all the same kind of object: sixteen rows of
 * sixteen characters, each character an index into `PALETTE`.
 *
 * `.` is transparent. The rest are named so a row can be read without counting.
 */


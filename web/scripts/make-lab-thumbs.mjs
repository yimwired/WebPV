// Cuts a small copy of every gallery card for the places that show one at
// thumbnail size: the package rows and the wide cards in the hero's lanes.
//
// The export serves images as they are (no resizing on request), so a 96px box
// holding the 1200px card downloads several times the bytes it can show. A row
// is 96x72 with the card cropped to fit, which scales the card to about 115px
// wide, or 346px on a 3x phone; a lane card is at most 210px wide, or 420px at
// 2x. These cards are screenshots with small text in them: cut to exactly that
// width they read visibly softer than the full card, so keep a margin and a
// higher quality.
//
// Each thumbnail gets its own content hash, because `public/_headers` caches this
// folder as immutable: changing WIDTH or QUALITY has to change the URL too.
//
// shoot-lab-cards.mjs runs this after a reshoot. To run it alone, from the repo root:
//   node web/scripts/make-lab-thumbs.mjs
import sharp from "sharp";
import { createHash } from "node:crypto";
import { mkdir, readdir, rm, stat, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const CARDS = fileURLToPath(new URL("../public/labs/cards/", import.meta.url));
const OUT = fileURLToPath(new URL("../public/labs/cards/thumbs/", import.meta.url));
const MANIFEST = fileURLToPath(new URL("../src/lib/lab-thumbs.ts", import.meta.url));

const WIDTH = 480;
const QUALITY = 86;

const files = (await readdir(CARDS)).filter((file) => file.endsWith(".webp")).sort();

// Everything is cut before anything is replaced, so a failure part way through
// leaves the last good set in place rather than half a folder.
const thumbs = await Promise.all(
  files.map(async (file) => ({
    file,
    slug: file.slice(0, -".webp".length),
    bytes: await sharp(`${CARDS}${file}`).resize({ width: WIDTH }).webp({ quality: QUALITY }).toBuffer(),
    cardBytes: (await stat(`${CARDS}${file}`)).size,
  })),
);

await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });
await Promise.all(thumbs.map(({ file, bytes }) => writeFile(`${OUT}${file}`, bytes)));

const versions = Object.fromEntries(
  thumbs.map(({ slug, bytes }) => [slug, createHash("sha1").update(bytes).digest("hex").slice(0, 8)]),
);

await writeFile(
  MANIFEST,
  [
    "// Generated by `node scripts/make-lab-thumbs.mjs`. Do not edit by hand.",
    "//",
    "// One content hash per thumbnail, appended to its URL: `public/_headers` caches",
    "// the folder as immutable, so new bytes need a new address.",
    "// สร้างจากสคริปต์ ห้ามแก้มือ",
    "",
    "export const labThumbVersions: Record<string, string> = " + JSON.stringify(versions, null, 2) + ";",
    "",
  ].join("\n"),
  "utf8",
);

const kilobytes = (bytes) => Math.round(bytes / 1024);
const total = (pick) => thumbs.reduce((sum, thumb) => sum + pick(thumb), 0);
console.log(
  `${thumbs.length} thumbnails at ${WIDTH}px: ${kilobytes(total((t) => t.bytes.length))}KB, ` +
    `cut from ${kilobytes(total((t) => t.cardBytes))}KB of cards`,
);
